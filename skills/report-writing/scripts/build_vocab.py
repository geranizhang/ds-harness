#!/usr/bin/env python3
"""Build or refresh the adapter's vocabulary whitelist (adapters/<name>/vocab.txt).

Auto section: headings, bold phrases, backticked identifiers and suffix-terms from the files listed in
adapter.json doc.vocab_sources (glossary / metrics / tables / exemplars). Regenerated every run.
Manual section: everything after "# --- manual ---" is preserved. Humans add accepted terms there.

Usage: build_vocab.py [--dry-run]
"""
import glob
import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "_shared"))
import harness_config as hc  # noqa: E402
sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate_doc import build_patterns, extract_terms  # noqa: E402

MANUAL_MARK = "# --- manual ---"


def terms_from_ref(path, pats, ignore):
    s = open(path, encoding="utf-8").read()
    t = set()
    for m in re.finditer(r"^#{1,6}\s+(.+)$", s, re.M):
        t |= extract_terms(m.group(1), pats, ignore)
        if pats.get("cjk"):
            t.add(m.group(1).strip().split("（")[0].split("(")[0].strip())
    for m in re.finditer(r"\*\*([^*\n]{2,40})\*\*", s):
        t |= extract_terms(m.group(1), pats, ignore)
    for m in re.finditer(r"`([^`\n]{2,60})`", s):
        tok = m.group(1).strip()
        if re.fullmatch(r"[A-Za-z][\w.]*", tok):
            t.add(tok)
    t |= extract_terms(s, pats, ignore)
    return t


def main():
    dry = "--dry-run" in sys.argv
    cfg = hc.load()
    doc = hc.get(cfg, "delivery.doc", {})
    pats = build_patterns(doc)
    ignore = set(doc.get("ascii_ignore") or [])
    out = hc.path(cfg, hc.get(cfg, "delivery.vocab", "delivery/vocab.txt"))
    auto = set()
    for pattern in hc.get(cfg, "delivery.vocab_sources", []):
        for f in glob.glob(str(hc.path(cfg, pattern))):
            auto |= terms_from_ref(f, pats, ignore)
    auto = {t for t in auto if len(t) >= 2 and not t.isdigit()}
    manual = []
    if out.exists():
        s = out.read_text(encoding="utf-8")
        if MANUAL_MARK in s:
            manual = [l for l in s.split(MANUAL_MARK, 1)[1].splitlines() if l.strip()]
    lines = ["# Team vocabulary: whitelist for validate_doc.py. Top half is regenerated by build_vocab.py; bottom half is kept.",
             "# --- auto ---"] + sorted(auto, key=lambda x: x.encode("utf-8")) + ["", MANUAL_MARK] + (manual or ["# add terms your team accepts that the auto section misses"])
    text = "\n".join(lines) + "\n"
    if dry:
        print(text)
    else:
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out}: auto {len(auto)} terms, manual {len(manual)} terms")


if __name__ == "__main__":
    main()
